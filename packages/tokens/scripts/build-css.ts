/* Generates dist/tokens.css from src/index.ts and checks contrast. Run: tsx scripts/build-css.ts */
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  palette, themes, space, radius, font, typography, size, material, z, motions, defaultMotion, SPRING_NAMES, springEasing, springDuration,
  duration, easing, contrast, type ThemeName,
} from '../src/index';

const out: string[] = ['/* Glass Layer tokens — generated by packages/tokens/scripts/build-css.ts. Do not edit. */'];
const decl = (k: string, v: string | number) => `  --gl-${k}: ${v};`;
const keyOf = (k: string | number) => String(k).replace('.', '_');

/* raw palette + scales (theme independent) */
const root: string[] = [];
for (const [hue, ramp] of Object.entries(palette)) for (const [step, hex] of Object.entries(ramp)) root.push(decl(`${hue}-${step}`, hex));
for (const [k, v] of Object.entries(space)) root.push(decl(`space-${keyOf(k)}`, v));
for (const [k, v] of Object.entries(radius)) root.push(decl(`radius-${k}`, v));
for (const [k, v] of Object.entries(font)) root.push(decl(`font-${k}`, v));
for (const [k, v] of Object.entries(size)) root.push(decl(`size-${k}`, v));
for (const [k, v] of Object.entries(material)) root.push(decl(`${k}`, v));
for (const [k, v] of Object.entries(z)) root.push(decl(`z-${k}`, v));
for (const [k, v] of Object.entries(duration)) root.push(decl(`duration-${k}`, `${v}ms`));
for (const [k, v] of Object.entries(easing)) root.push(decl(`ease-${k}`, v));
/* motion personality: the default on :root, each one also as [data-gl-motion] so it can be scoped */
const motionDecls = (m: (typeof motions)[keyof typeof motions]) => [
  ...SPRING_NAMES.flatMap((n) => [decl(`spring-${n}`, springEasing(m[n])), decl(`spring-${n}-duration`, `${springDuration(m[n])}ms`)]),
  decl('motion-squash', m.squash), decl('motion-gel', m.gel), decl('motion-lag', m.lag),
];
root.push(...motionDecls(motions[defaultMotion]));
for (const [name, [fs, lh, fw, tr]] of Object.entries(typography)) {
  root.push(decl(`text-${name}-size`, `${fs}px`), decl(`text-${name}-line`, `${lh}px`), decl(`text-${name}-weight`, fw), decl(`text-${name}-tracking`, `${tr}em`));
}
/* shadows read the theme's shadow colour/strength */
root.push(decl('shadow-sm', '0 1px 2px rgba(var(--gl-shadow-color), calc(0.06 * var(--gl-shadow-strength))), 0 2px 8px rgba(var(--gl-shadow-color), calc(0.05 * var(--gl-shadow-strength)))'));
root.push(decl('shadow-md', '0 1px 3px rgba(var(--gl-shadow-color), calc(0.07 * var(--gl-shadow-strength))), 0 8px 24px rgba(var(--gl-shadow-color), calc(0.1 * var(--gl-shadow-strength)))'));
root.push(decl('shadow-lg', '0 2px 6px rgba(var(--gl-shadow-color), calc(0.08 * var(--gl-shadow-strength))), 0 20px 48px rgba(var(--gl-shadow-color), calc(0.16 * var(--gl-shadow-strength)))'));
out.push(':root {', ...root, '}');
for (const [name, m] of Object.entries(motions)) out.push(`[data-gl-motion="${name}"] {`, ...motionDecls(m), '}');

const block = (sel: string, t: ThemeName, scheme: 'light' | 'dark') =>
  [`${sel} {`, `  color-scheme: ${scheme};`, ...Object.entries(themes[t]).map(([k, v]) => decl(k, v)), '}'].join('\n');

out.push(block(':root, [data-gl-theme="light"]', 'light', 'light'));
out.push(block('[data-gl-theme="dark"]', 'dark', 'dark'));
out.push(block('[data-gl-theme="light-hc"]', 'light-hc', 'light'));
out.push(block('[data-gl-theme="dark-hc"]', 'dark-hc', 'dark'));
/* follow the system when no theme is forced */
const sys = (q: string, t: ThemeName, scheme: 'light' | 'dark') =>
  `@media ${q} {\n${block(':root:not([data-gl-theme])', t, scheme).replace(/^/gm, '  ')}\n}`;
out.push(sys('(prefers-color-scheme: dark)', 'dark', 'dark'));
out.push(sys('(prefers-contrast: more) and (prefers-color-scheme: light)', 'light-hc', 'light'));
out.push(sys('(prefers-contrast: more) and (prefers-color-scheme: dark)', 'dark-hc', 'dark'));

mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
writeFileSync(new URL('../dist/tokens.css', import.meta.url), out.join('\n') + '\n');

/* ---- contrast report (WCAG 2): fails the build if a required pair is below its target ---- */
const pairs: [string, string, number][] = [
  ['label', 'bg', 7], ['label', 'bg-elevated', 7], ['label-secondary', 'bg', 4.5], ['label-secondary', 'bg-grouped', 4.5],
  ['label-tertiary', 'bg', 3], ['accent-text', 'bg', 4.5], ['accent-text', 'bg-elevated', 4.5], ['on-accent', 'accent', 4.5],
  ['danger-text', 'bg', 4.5], ['success-text', 'bg', 4.5], ['info-text', 'bg', 4.5], ['warning-text', 'bg', 4.5],
  ['focus-ring', 'bg', 3],
];
let failed = 0;
for (const t of Object.keys(themes) as ThemeName[]) {
  const th = themes[t] as Record<string, string>;
  const row = pairs.map(([fg, bg, min]) => {
    const r = contrast(th[fg], th[bg]);
    const target = t.endsWith('hc') ? Math.max(min, min >= 4.5 ? 7 : 4.5) : min;
    if (r < target) failed++;
    return `${r < target ? '✗' : '✓'} ${fg}/${bg} ${r.toFixed(2)}${r < target ? ` (<${target})` : ''}`;
  });
  console.log(`[${t}] ${row.join('  ')}`);
}
console.log(`tokens.css written · contrast ${failed ? failed + ' FAILED' : 'all passed'}`);
if (failed) process.exitCode = 1;
