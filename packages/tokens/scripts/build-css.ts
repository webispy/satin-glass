/* Generates dist/tokens.css from src/index.ts and checks contrast. Run: tsx scripts/build-css.ts */
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  palette, themes, space, radius, font, typography, controlText, size, material, z, motions, defaultMotion, reducedMotion, SPRING_NAMES, springEasing, springDuration,
  duration, easing, contrast, type ThemeName,
} from '../src/index';

const out: string[] = ['/* Satin Glass tokens — generated by packages/tokens/scripts/build-css.ts. Do not edit. */'];
const decl = (k: string, v: string | number) => `  --sg-${k}: ${v};`;
const keyOf = (k: string | number) => String(k).replace('.', '_');

/* raw palette + scales (theme independent) */
const root: string[] = [];
for (const [hue, ramp] of Object.entries(palette)) for (const [step, hex] of Object.entries(ramp)) root.push(decl(`${hue}-${step}`, hex));
for (const [k, v] of Object.entries(space)) root.push(decl(`space-${keyOf(k)}`, v));
for (const [k, v] of Object.entries(radius)) root.push(decl(`radius-${k}`, v));
for (const [k, v] of Object.entries(font)) root.push(decl(`font-${k}`, v));
for (const [k, v] of Object.entries(size)) root.push(decl(`size-${k}`, v));
for (const [k, v] of Object.entries(material)) root.push(decl(`${k}`, v));
for (const [k, v] of Object.entries(z)) root.push(decl(`z-${k}`, v));
for (const [k, v] of Object.entries(duration)) root.push(decl(`duration-${k}`, `${v}ms`));
for (const [k, v] of Object.entries(easing)) root.push(decl(`ease-${k}`, v));
/* motion personality: the default on :root, each one also as [data-sg-motion] so it can be scoped */
const motionDecls = (m: (typeof motions)[keyof typeof motions]) => [
  ...SPRING_NAMES.flatMap((n) => [decl(`spring-${n}`, springEasing(m[n])), decl(`spring-${n}-duration`, `${springDuration(m[n])}ms`)]),
  decl('motion-squash', m.squash), decl('motion-gel', m.gel), decl('motion-lag', m.lag),
];
root.push(...motionDecls(motions[defaultMotion]));
for (const [name, [fs, lh, fw, tr]] of [...Object.entries(typography), ...Object.entries(controlText)]) {
  root.push(decl(`text-${name}-size`, `${fs}px`), decl(`text-${name}-line`, `${lh}px`), decl(`text-${name}-weight`, fw), decl(`text-${name}-tracking`, `${tr}em`));
}
out.push(':root {', ...root, '}');
/* depth and layers (design-language.md, 깊이와 레이어). Light comes from above: what is raised is lit on its top edge,
   shaded on its bottom edge and casts a soft shadow; what is recessed is shaded inside its top edge. Declared on every
   theme element so they take that theme's shadow colour and glass values. High contrast flattens them (outlines
   carry the shapes there).
     inset   a groove: tracks, rails and columns a value moves along (switch, slider, progress, segmented, stepper,
             a wheel's column) and fields a value goes into
     raised  something lifted off its surface that you hold or that marks the choice (knobs, thumbs, the segmented
             chip, the wheel lens); raised-accent and sheen-accent for a chosen accent bead (a day, a month, a weekday) */
/* shadows read the theme's shadow colour and strength, so they are declared with the depth tokens on every theme
   element (a var() is resolved where the property is declared: on :root alone, a dark island kept light shadows) */
const depth = [
  decl('shadow-sm', '0 1px 2px rgba(var(--sg-shadow-color), calc(0.06 * var(--sg-shadow-strength))), 0 2px 8px rgba(var(--sg-shadow-color), calc(0.05 * var(--sg-shadow-strength)))'),
  decl('shadow-md', '0 1px 3px rgba(var(--sg-shadow-color), calc(0.07 * var(--sg-shadow-strength))), 0 8px 24px rgba(var(--sg-shadow-color), calc(0.1 * var(--sg-shadow-strength)))'),
  decl('shadow-lg', '0 2px 6px rgba(var(--sg-shadow-color), calc(0.08 * var(--sg-shadow-strength))), 0 20px 48px rgba(var(--sg-shadow-color), calc(0.16 * var(--sg-shadow-strength)))'),
  decl('depth-inset', 'inset 0 1px 2px rgba(var(--sg-shadow-color), calc(0.14 * var(--sg-shadow-strength))), inset 0 0 0 0.5px rgba(var(--sg-shadow-color), calc(0.05 * var(--sg-shadow-strength)))'),
  decl('depth-raised', '0 1px 2px rgba(var(--sg-shadow-color), calc(0.12 * var(--sg-shadow-strength))), 0 3px 8px -2px rgba(var(--sg-shadow-color), calc(0.14 * var(--sg-shadow-strength))), inset 0 1px 0 var(--sg-glass-rim-lit), inset 0 -1px 0 var(--sg-glass-rim-shade)'),
  decl('depth-raised-accent', '0 1px 2px color-mix(in oklab, var(--sg-accent) 45%, transparent), 0 3px 8px -4px color-mix(in oklab, var(--sg-accent) 55%, transparent), inset 0 1px 0 rgba(255, 255, 255, 0.3), inset 0 -1px 0 rgba(0, 0, 0, 0.12)'),   /* a short shadow, not a glow: beads come in rows (weekdays) */
  decl('depth-sheen', 'linear-gradient(180deg, var(--sg-glass-depth), rgba(255, 255, 255, 0) 62%)'),
  decl('depth-sheen-accent', 'linear-gradient(180deg, rgba(255, 255, 255, 0.24), rgba(255, 255, 255, 0) 58%)'),
];
/* the raised surface itself: the plain surface in light themes; in dark ones a lighter tint, so a raised thing reads
   lighter than what it sits on (the segmented control's chosen segment, the wheel lens) */
depth.push(decl('depth-raised-bg', 'var(--sg-surface)'));
/* a handle that rides a rail (switch knob, slider thumb) stays light in every theme: it must stand apart from both
   the empty rail and the accent fill under it (see design-language.md 8. 깊이와 레이어, 손잡이); high contrast
   outlines it through --sg-depth-raised */
depth.push(decl('depth-handle-bg', 'linear-gradient(180deg, #ffffff, #f3f4f8)'));
/* a hairline round anything raised, so a light chip keeps its edge on a light rail (none in high contrast: the outline does it) */
depth.push(decl('depth-raised-edge', '0 0 0 0.5px rgba(var(--sg-shadow-color), calc(0.06 * var(--sg-shadow-strength)))'));
/* a page pushed over another (navigation stack): a hairline and a soft shadow on its leading edge */
depth.push(decl('shadow-edge', '-1px 0 0 var(--sg-separator), -16px 0 32px rgba(var(--sg-shadow-color), calc(0.08 * var(--sg-shadow-strength)))'));
/* a flat selection on glass (tab bar, sidebar): no outline normally; in high contrast its tint gives way to one */
depth.push(decl('selection-outline', '0 0 0 0 transparent'));
out.push(':root, [data-sg-theme] {', ...depth, '}');
out.push('[data-sg-theme^="dark"] {', decl('depth-raised-bg', 'var(--sg-fill-strong)'), '}');
out.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-sg-theme]) {', '  ' + decl('depth-raised-bg', 'var(--sg-fill-strong)'), '  }', '}');
/* high contrast: depth turns into outlines, so every groove, knob and chosen thing keeps a visible edge (3:1 for
   non-text) through the same tokens — no component needs its own high-contrast rule */
const hcDepth = [
  decl('depth-inset', 'inset 0 0 0 1px var(--sg-separator-strong)'),
  decl('depth-raised', 'inset 0 0 0 1.5px var(--sg-label)'), decl('depth-raised-accent', 'inset 0 0 0 1.5px var(--sg-label)'),
  decl('depth-sheen', 'none'), decl('depth-sheen-accent', 'none'),
  decl('selection-outline', 'inset 0 0 0 1.5px var(--sg-label)'),
  decl('depth-raised-edge', '0 0 0 0 transparent'),
];
out.push('[data-sg-theme$="-hc"] {', ...hcDepth, '}');
out.push('@media (prefers-contrast: more) {', '  :root:not([data-sg-theme]) {', ...hcDepth.map((l) => '  ' + l), '  }', '}');
for (const [name, m] of Object.entries(motions)) out.push(`[data-sg-motion="${name}"] {`, ...motionDecls(m), '}');
/* reduced motion wins over any personality inside it, up to the nearest area that says "false" (@scope's lower
   bound): the nearest setting decides, as it does for the JS springs (prefersReducedMotion). ThemeProvider and
   Portal write the resolved setting; the media query covers pages that use the CSS without them */
const reduced = motionDecls(reducedMotion);
out.push('@scope ([data-sg-reduce-motion="true"]) to ([data-sg-reduce-motion="false"]) {', '  :scope, [data-sg-motion] {', ...reduced.map((l) => '  ' + l), '  }', '}');
out.push('@media (prefers-reduced-motion: reduce) {', '  @scope (:root) to ([data-sg-reduce-motion="false"]) {', '    :scope, [data-sg-motion] {', ...reduced.map((l) => '    ' + l), '    }', '  }', '}');

const block = (sel: string, t: ThemeName, scheme: 'light' | 'dark') =>
  [`${sel} {`, `  color-scheme: ${scheme};`, ...Object.entries(themes[t]).map(([k, v]) => decl(k, v)), '}'].join('\n');

out.push(block(':root, [data-sg-theme="light"]', 'light', 'light'));
out.push(block('[data-sg-theme="dark"]', 'dark', 'dark'));
out.push(block('[data-sg-theme="light-hc"]', 'light-hc', 'light'));
out.push(block('[data-sg-theme="dark-hc"]', 'dark-hc', 'dark'));
/* follow the system when no theme is forced */
const sys = (q: string, t: ThemeName, scheme: 'light' | 'dark') =>
  `@media ${q} {\n${block(':root:not([data-sg-theme])', t, scheme).replace(/^/gm, '  ')}\n}`;
out.push(sys('(prefers-color-scheme: dark)', 'dark', 'dark'));
out.push(sys('(prefers-contrast: more) and (prefers-color-scheme: light)', 'light-hc', 'light'));
out.push(sys('(prefers-contrast: more) and (prefers-color-scheme: dark)', 'dark-hc', 'dark'));

mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
writeFileSync(new URL('../dist/tokens.css', import.meta.url), out.join('\n') + '\n');

/* ---- contrast report (WCAG 2): fails the build if a required pair is below its target ---- */
const pairs: [string, string, number][] = [
  ['label', 'bg', 7], ['label', 'bg-elevated', 7], ['label-secondary', 'bg', 4.5], ['label-secondary', 'bg-grouped', 4.5],
  ['label-tertiary', 'bg', 4.5], ['label-tertiary', 'surface', 4.5], ['label-tertiary', 'bg-grouped', 4.5], ['accent-text', 'bg', 4.5], ['accent-text', 'bg-elevated', 4.5], ['on-accent', 'accent', 4.5],
  ['danger-text', 'bg', 4.5], ['success-text', 'bg', 4.5], ['info-text', 'bg', 4.5], ['warning-text', 'bg', 4.5],
  ['focus-ring', 'bg', 3],
  /* data marks (lines, bars, slices) are non-text graphics: 3:1 against the card they sit on */
  ['chart-1', 'surface', 3], ['chart-2', 'surface', 3], ['chart-3', 'surface', 3], ['chart-4', 'surface', 3], ['chart-5', 'surface', 3], ['chart-6', 'surface', 3],
];
/* a few pairs need a composited background (translucent fill over the surface) or plain white text */
const composite = (fill: string, under: string) => {
  const m = fill.match(/rgba?\((\d+), (\d+), (\d+)(?:, ([\d.]+))?\)/);
  if (!m) return fill;
  const a = m[4] === undefined ? 1 : +m[4];
  const u = [1, 3, 5].map((i) => parseInt(under.slice(i, i + 2), 16));
  return '#' + [1, 2, 3].map((i, k) => Math.round(+m[i] * a + u[k] * (1 - a)).toString(16).padStart(2, '0')).join('');
};
pairs.push(['accent-on-soft', 'accent-soft@surface', 4.5], ['danger-on-soft', 'danger-soft@surface', 4.5], ['#ffffff', 'danger-fill', 4.5]);
/* states and composited backgrounds: a filled button hovered and pressed, a placeholder inside a field on each
   page background, white text on clear glass over a white photo */
pairs.push(['on-accent', 'accent-hover', 4.5], ['on-accent', 'accent-pressed', 4.5],
  ['label-secondary', 'fill@bg', 4.5], ['label-secondary', 'fill@surface', 4.5], ['label-secondary', 'fill@bg-grouped', 4.5],
  ['#ffffff', 'glass-fill-clear@#ffffff', 4.5]);
/* high contrast only: the outline a groove or field gets is non-text and must reach 3:1 against the page */
const hcOnly = new Set(['separator-strong/bg']);
pairs.push(['separator-strong', 'bg', 3]);
let failed = 0;
for (const t of Object.keys(themes) as ThemeName[]) {
  const th = { ...(themes[t] as Record<string, string>), '#ffffff': '#ffffff' } as Record<string, string>;
  for (const [, bg] of pairs) if (bg.includes('@')) { const [f, u] = bg.split('@'); th[bg] = composite(th[f], th[u]); }
  const row = pairs.filter(([fg, bg]) => t.endsWith('hc') || !hcOnly.has(`${fg}/${bg}`)).map(([fg, bg, min]) => {
    const r = contrast(th[fg], th[bg]);
    const target = t.endsWith('hc') && !hcOnly.has(`${fg}/${bg}`) ? Math.max(min, min >= 4.5 ? 7 : 4.5) : min;
    if (r < target) failed++;
    return `${r < target ? '✗' : '✓'} ${fg}/${bg} ${r.toFixed(2)}${r < target ? ` (<${target})` : ''}`;
  });
  console.log(`[${t}] ${row.join('  ')}`);
}
console.log(`tokens.css written · contrast ${failed ? failed + ' FAILED' : 'all passed'}`);
if (failed) process.exitCode = 1;
