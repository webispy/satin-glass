/* The motion tables in docs/design-language.md (chapter 6), computed from the tokens so the numbers cannot drift
   from the springs. `tsx scripts/motion-doc.ts` rewrites the block between the markers; `--check` (run by the
   build) fails when the document is out of date. The formulas for the personality effects mirror the components:
     segmented / tab indicator   height  1 - squash                     (core/src/bridge.ts)
     switch knob on arrival      width   1 - squash × 1.1               (react/src/controls.tsx)
     slider knob, fast drag      width   1 + gel × 1.6                  (react/src/controls.tsx)
     menu bloom start            1 - (1 - f) × (0.45 + 0.55 × squash / 0.14), at least 0.15, f = 0.6 × 0.3
                                                                        (core/src/overlay.ts) */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SPRING_NAMES, motions, reducedMotion, springAt, springDuration, type MotionName, type SpringParams } from '../src/index';

const DOC = fileURLToPath(new URL('../../../docs/design-language.md', import.meta.url));
const START = '<!-- motion-table:start (generated by packages/tokens/scripts/motion-doc.ts; do not edit by hand) -->';
const END = '<!-- motion-table:end -->';

/** time to reach 90 % of the way (ms) */
const t90 = (s: SpringParams) => { for (let t = 0; t < 3; t += 0.001) if (springAt(s, t) >= 0.9) return Math.round(t * 1000); return 3000; };
/** largest overshoot past the target (%) */
const over = (s: SpringParams) => { let m = 0; for (let t = 0; t < 3; t += 0.001) m = Math.max(m, springAt(s, t) - 1); return m * 100; };
const pct = (x: number) => (x < 0.05 ? '0' : `${x.toFixed(1)}%`);
const NAMES: MotionName[] = ['calm', 'lively', 'playful'];
const LABEL: Record<MotionName, string> = { calm: 'calm', lively: '**lively**', playful: 'playful' };

export function motionTable(): string {
  const cell = (s: SpringParams) => `${t90(s)} · ${pct(over(s))} · ${springDuration(s)}`;
  const rows = SPRING_NAMES.map((n) => `| ${n} | ${NAMES.map((m) => cell(motions[m][n])).join(' | ')} | ${cell(reducedMotion[n])} |`);
  const fx = (m: MotionName) => {
    const { squash, gel, lag } = motions[m];
    const k = squash / 0.14, reach = 0.45 + 0.55 * k, grow = (f: number) => Math.max(0.15, 1 - (1 - f) * reach);
    return `| ${LABEL[m]} | ${squash} | ${(1 - squash).toFixed(2)} | ${(1 - squash * 1.1).toFixed(2)} | ${(1 + gel * 1.6).toFixed(2)} | ${lag ? `${Math.round(lag * 1000)}ms` : '없음'} | ${grow(0.6).toFixed(2)} × ${grow(0.3).toFixed(2)} |`;
  };
  return [
    START,
    '',
    '스프링마다 **90% 도달 · 최대 넘침 · 정착(목표 ±0.1% 안에 머무는 시점)**, 단위 ms. 정착은 눈에 띄는 움직임이 멎는 때보다 늦다(꼬리는 1px 미만).',
    '',
    '| 스프링 | calm | **lively** | playful | 동작 줄이기 |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    '성격이 바꾸는 모양(움직이는 동안의 가장 큰 값).',
    '',
    '| 성격 | squash | 세그먼트·탭 표시 최소 높이 | 스위치 손잡이 도착 시 최소 폭 | 슬라이더 손잡이 최대 폭(빠르게 끌 때) | 손가락을 따라오는 지연(lag) | 메뉴가 피어나기 시작하는 크기(가로 × 세로) |',
    '|---|---|---|---|---|---|---|',
    ...NAMES.map(fx),
    '',
    END,
  ].join('\n');
}

const doc = readFileSync(DOC, 'utf8');
const a = doc.indexOf('<!-- motion-table:start'), b = doc.indexOf(END);
if (a < 0 || b < 0) { console.error(`motion-doc: markers not found in ${DOC}`); process.exit(1); }
const next = doc.slice(0, a) + motionTable() + doc.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== doc) { console.error('motion-doc: docs/design-language.md motion tables are out of date — run `pnpm docs:motion`'); process.exit(1); }
} else if (next !== doc) { writeFileSync(DOC, next); console.log('motion-doc: updated docs/design-language.md'); }
